"""Business case: write the one-page case, docs/BUSINESS_CASE.md, with every number filled from the tool's facts.

What: fill_template() replaces each [[fact.key]] or [[config:dotted.key]] placeholder in
      ewu/business_case_template.md with that value (an optional |format such as |,.0f or |.2f sets how
      it prints; a trailing .N on a config key picks item N of a list). write_business_case() writes the doc.
Why:  judges found the one-pager and the tool disagreeing (9.8% against 26.18% flagged). Typing numbers
      into prose is how that happens. Here the prose is fixed and the numbers can only come from the
      facts the code wrote, so a rerun updates the case and a missing fact stops the build.
How:  one regular expression over the template; a key absent from facts/facts.json or config/ewu.yaml
      raises with its name, so nothing is ever left blank or guessed. The note line at the top says the
      file is generated. checks/trace_numbers.py then traces every number in the output on its own.
"""
import sys
from pathlib import Path
if str(Path(__file__).resolve().parent.parent) not in sys.path:
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import json
import re
from ewu import ROOT, read_config

TEMPLATE = ROOT / "ewu" / "business_case_template.md"
OUTPUT = ROOT / "docs" / "BUSINESS_CASE.md"
PLACEHOLDER = re.compile(r"\[\[([^\]|]+)(?:\|([^\]]+))?\]\]")
NOTE = ("Generated by `bin/ewu case` from facts/facts.json and config/ewu.yaml; edit "
        "ewu/business_case_template.md, never this file.")


def config_lookup(dotted, config):
    """Value of a config input; 'a.b.N' picks item N when the value is a list."""
    parts = dotted.split(".")
    node = config
    for i, part in enumerate(parts):
        if isinstance(node, dict) and part in node:
            node = node[part]
            continue
        if isinstance(node, dict) and "value" in node and isinstance(node["value"], list) and part.isdigit():
            return node["value"][int(part)]
        raise KeyError(f"config has no input '{dotted}'")
    if not (isinstance(node, dict) and "value" in node):
        raise KeyError(f"config '{dotted}' is a block, not an input")
    return node["value"]


def shown_value(value, form):
    """The value as the doc prints it: the given format, else ints with commas and floats as recorded."""
    if form:
        return format(value, form)
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return str(value)
    return f"{value:,}" if isinstance(value, int) else f"{value:g}" if abs(value) >= 1e4 else str(value)


def fill_template(text, facts, config):
    """Replace every placeholder; raise on the first key that has no value."""
    def replace(match):
        key, form = match.group(1).strip(), match.group(2)
        if key == "note":
            return NOTE
        if key.startswith("config:"):
            return shown_value(config_lookup(key[len("config:"):], config), form)
        if key not in facts:
            raise KeyError(f"facts/facts.json has no '{key}'; rerun the step that records it")
        return shown_value(facts[key]["value"], form)
    return PLACEHOLDER.sub(replace, text)


def write_business_case():
    facts = json.loads((ROOT / "facts" / "facts.json").read_text())
    OUTPUT.write_text(fill_template(TEMPLATE.read_text(), facts, read_config()))
    return OUTPUT


def main():
    path = write_business_case()
    print(f"Business case written from facts: {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
